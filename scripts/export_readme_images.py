"""Collect the images the README shows, so a reviewer sees the findings without running anything.

    uv run python scripts/export_readme_images.py

Two sources, and neither of them redraws anything:

**Charts come out of the executed notebooks.** The figure in the README is byte for
byte the figure in the notebook, because it is lifted from that notebook's committed
output rather than regenerated by a copy of its plotting code. A chart in the README
that had drifted from the analysis it illustrates would be worse than no chart.

**Dashboard screenshots come from the real pages**, loaded in headless Chromium from
`site/data`. CLAUDE.md §13 leaves hosting undecided, so screenshots are how a
reviewer sees the dashboard — which makes them part of the deliverable, not decoration.

Either half skips itself when its inputs are missing, so this runs on a machine with
no browser or no exported site data and tells you what it skipped.
"""

from __future__ import annotations

import base64
import json
import socket
import threading
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
IMAGES = REPO_ROOT / "docs" / "images"
SITE = REPO_ROOT / "site"

# (notebook, zero-based cell index, output filename, what it shows)
FIGURES = [
    (
        "02_points_vs_xpts",
        10,
        "02-gap-persistence.png",
        "first-half vs second-half points-over-xPTS, one point per club-season",
    ),
    (
        "02_points_vs_xpts",
        15,
        "02-regression-to-mean.png",
        "clubs grouped by first-half gap, and where each group's second half landed",
    ),
    (
        "03_is_finishing_repeatable",
        10,
        "03-finishing-vs-volume.png",
        "season-to-season repeatability: finishing against shot volume, same players",
    ),
]

PAGES = [
    ("index.html", "dashboard-league-table.png", {"width": 1280, "height": 1120}),
    ("team.html", "dashboard-team.png", {"width": 1280, "height": 1120}),
    ("players.html", "dashboard-players.png", {"width": 1280, "height": 1120}),
    ("shots.html", "dashboard-shots.png", {"width": 1280, "height": 1240}),
]


def export_figures() -> list[str]:
    """Lift each named figure out of its notebook's committed output."""
    written = []
    for notebook, index, filename, _caption in FIGURES:
        path = REPO_ROOT / "notebooks" / f"{notebook}.ipynb"
        cells = json.loads(path.read_text())["cells"]
        outputs = cells[index].get("outputs", [])
        png = next(
            (out["data"]["image/png"] for out in outputs if "image/png" in out.get("data", {})),
            None,
        )
        if png is None:
            print(f"  ! {notebook} cell {index} has no image — was the notebook re-run?")
            continue
        target = IMAGES / filename
        target.write_bytes(base64.b64decode(png))
        written.append(filename)
        print(f"  {filename:32s} <- {notebook} cell {index}")
    return written


def export_screenshots() -> list[str]:
    """Load each dashboard page in a headless browser and photograph it."""
    if not (SITE / "data" / "meta.json").exists():
        print("  ! site/data is not exported — run scripts/export_site_data.py first")
        return []
    try:
        from playwright.sync_api import sync_playwright
    except ImportError:
        print("  ! playwright is not installed — skipping the dashboard screenshots")
        return []

    import http.server
    from functools import partial

    with socket.socket() as probe:
        probe.bind(("127.0.0.1", 0))
        port = probe.getsockname()[1]
    handler = partial(http.server.SimpleHTTPRequestHandler, directory=str(SITE))
    httpd = http.server.ThreadingHTTPServer(("127.0.0.1", port), handler)
    threading.Thread(target=httpd.serve_forever, daemon=True).start()

    written = []
    try:
        with sync_playwright() as driver:
            try:
                browser = driver.chromium.launch()
            except Exception as exc:
                print(f"  ! Chromium will not start ({type(exc).__name__}) — skipping screenshots")
                print("    uv run playwright install --with-deps chromium")
                return []
            for page_name, filename, viewport in PAGES:
                page = browser.new_page(viewport=viewport, device_scale_factor=2)
                page.goto(f"http://127.0.0.1:{port}/{page_name}", wait_until="networkidle")
                # Let the vendored fonts land before photographing the page.
                page.wait_for_timeout(500)
                page.screenshot(path=str(IMAGES / filename))
                page.close()
                written.append(filename)
                print(f"  {filename:32s} <- {page_name}")
            browser.close()
    finally:
        httpd.shutdown()
        httpd.server_close()
    return written


def main() -> int:
    IMAGES.mkdir(parents=True, exist_ok=True)
    print(f"Writing to {IMAGES.relative_to(REPO_ROOT)}")
    print("Charts, from the notebooks' committed outputs:")
    figures = export_figures()
    print("Screenshots, from the real dashboard:")
    shots = export_screenshots()

    total = len(figures) + len(shots)
    print(f"\n{total} image(s) written")
    if len(figures) < len(FIGURES) or len(shots) < len(PAGES):
        print("Some were skipped — the README may show stale or missing images.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
